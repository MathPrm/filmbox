-- M1.2 & M1.3 : Création des listes
CREATE TABLE listes (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id INTEGER NOT NULL REFERENCES utilisateurs(id) ON DELETE CASCADE,
    titre          VARCHAR(100) NOT NULL,
    est_publique   BOOLEAN NOT NULL DEFAULT FALSE,
    cree_le        DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE liste_films (
    liste_id INTEGER NOT NULL REFERENCES listes(id) ON DELETE CASCADE,
    film_id  INTEGER NOT NULL REFERENCES films(id) ON DELETE CASCADE,
    position INTEGER NOT NULL CHECK (position > 0),
    PRIMARY KEY (liste_id, film_id),
    UNIQUE (liste_id, position)
);

